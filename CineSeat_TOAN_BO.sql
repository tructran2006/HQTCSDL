        v_show,
        '[' || v_seat || ']',
        NULL,
        v_id,
        v_total,
        v_exp
    );

    -- 4. Thanh toan gia lap
    pkg_booking.pr_confirm(v_id, 'DEMO_QR');

    -- 5. Kiem tra trang thai don, ghe va thanh toan
    SELECT COUNT(*)
    INTO v_good
    FROM bookings b
    JOIN payments p
        ON p.booking_id = b.booking_id
    JOIN showtime_seats ss
        ON ss.booking_id = b.booking_id
    WHERE b.booking_id = v_id
      AND b.status = 'PAID'
      AND p.payment_status = 'PAID'
      AND p.method = 'DEMO_QR'
      AND p.amount = b.total_amount
      AND ss.status = 'SOLD'
      AND ss.seat_id = v_seat;

    -- 6. Kiem tra lich su thay doi trang thai
    SELECT COUNT(*)
    INTO v_audit
    FROM booking_audit
    WHERE booking_id = v_id
      AND new_status IN ('HELD', 'PAID');

    -- 7. Danh gia ket qua
    IF v_good = 1 AND v_audit >= 2 THEN
        DBMS_OUTPUT.PUT_LINE('TC05: PASS');
        DBMS_OUTPUT.PUT_LINE('Booking ID: ' || v_id);
        DBMS_OUTPUT.PUT_LINE('Trang thai don: PAID');
        DBMS_OUTPUT.PUT_LINE('Trang thai ghe: SOLD');
        DBMS_OUTPUT.PUT_LINE('Thanh toan: DEMO_QR');
        DBMS_OUTPUT.PUT_LINE('So ban ghi Audit: ' || v_audit);
        DBMS_OUTPUT.PUT_LINE('Tong tien: ' || v_total);
    ELSE
        DBMS_OUTPUT.PUT_LINE('TC05: FAIL');
        DBMS_OUTPUT.PUT_LINE('Payment check: ' || v_good);
        DBMS_OUTPUT.PUT_LINE('Audit count: ' || v_audit);
    END IF;

    -- 8. Hoan tac de khong anh huong du lieu demo
    ROLLBACK TO tc05_start;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('TC05: FAIL - ' || SQLERRM);
        ROLLBACK TO tc05_start;
END;
