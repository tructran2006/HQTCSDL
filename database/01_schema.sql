-- 1. BẢNG NGƯỜI DÙNG HỆ THỐNG
CREATE TABLE app_users (
  user_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  full_name     NVARCHAR2(120) NOT NULL,
  email         VARCHAR2(180) NOT NULL UNIQUE,
  phone         VARCHAR2(20),
  created_at    TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);

-- 2. BẢNG PHIM
CREATE TABLE movies (
  movie_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  title         NVARCHAR2(160) NOT NULL,
  genre         NVARCHAR2(80) NOT NULL,
  duration_min  NUMBER(4) NOT NULL CHECK (duration_min BETWEEN 30 AND 300),
  age_rating    VARCHAR2(10) DEFAULT 'P' NOT NULL,
  synopsis      NVARCHAR2(900),
  poster_file   VARCHAR2(100),
  is_active     NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1))
);

-- 3. BẢNG CỤM RẠP
CREATE TABLE cinemas (
  cinema_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  cinema_name   NVARCHAR2(120) NOT NULL,
  address       NVARCHAR2(260) NOT NULL
);

-- 4. BẢNG PHÒNG CHIẾU
CREATE TABLE rooms (
  room_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  cinema_id     NUMBER NOT NULL REFERENCES cinemas(cinema_id),
  room_name     NVARCHAR2(50) NOT NULL,
  CONSTRAINT uq_cinema_room UNIQUE (cinema_id, room_name)
);

-- 5. BẢNG GHẾ VẬT LÝ TRONG PHÒNG
CREATE TABLE seats (
  seat_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  room_id       NUMBER NOT NULL REFERENCES rooms(room_id),
  row_label     VARCHAR2(2) NOT NULL,
  seat_number   NUMBER(3) NOT NULL CHECK(seat_number BETWEEN 1 AND 40),
  seat_type     VARCHAR2(15) DEFAULT 'STANDARD' NOT NULL
                  CHECK (seat_type IN ('STANDARD','VIP')),
  CONSTRAINT uq_room_seat UNIQUE (room_id, row_label, seat_number)
);

-- 6. BẢNG SUẤT CHIẾU
CREATE TABLE showtimes (
  showtime_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  movie_id      NUMBER NOT NULL REFERENCES movies(movie_id),
  room_id       NUMBER NOT NULL REFERENCES rooms(room_id),
  start_at      TIMESTAMP NOT NULL,
  end_at        TIMESTAMP NOT NULL,
  base_price    NUMBER(12,0) NOT NULL CHECK (base_price > 0),
  is_active     NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
  CONSTRAINT chk_showtime_period CHECK (end_at > start_at),
  CONSTRAINT uq_room_start UNIQUE (room_id, start_at)
);

-- 7. BẢNG MÃ KHUYẾN MÃI
CREATE TABLE promotions (
  promotion_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  promo_code    VARCHAR2(30) NOT NULL UNIQUE,
  discount_pct  NUMBER(5,2) NOT NULL CHECK (discount_pct BETWEEN 0 AND 50),
  valid_until   DATE NOT NULL,
  is_active     NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1))
);

-- 8. BẢNG ĐƠN ĐẶT VÉ
CREATE TABLE bookings (
  booking_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id       NUMBER NOT NULL REFERENCES app_users(user_id),
  showtime_id   NUMBER NOT NULL REFERENCES showtimes(showtime_id),
  promotion_id  NUMBER REFERENCES promotions(promotion_id),
  status        VARCHAR2(15) DEFAULT 'HELD' NOT NULL
                  CHECK(status IN ('HELD','PAID','CANCELLED','EXPIRED')),
  total_amount  NUMBER(12,0) NOT NULL CHECK(total_amount >= 0),
  created_at    TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  expires_at    TIMESTAMP NOT NULL,
  paid_at       TIMESTAMP
);

-- 9. BẢNG TRẠNG THÁI GHẾ THEO SUẤT CHIẾU (NGUỒN SỰ THẬT)
CREATE TABLE showtime_seats (
  showtime_id   NUMBER NOT NULL REFERENCES showtimes(showtime_id),
  seat_id       NUMBER NOT NULL REFERENCES seats(seat_id),
  status        VARCHAR2(15) DEFAULT 'AVAILABLE' NOT NULL
                  CHECK(status IN ('AVAILABLE','HELD','SOLD')),
  booking_id    NUMBER REFERENCES bookings(booking_id),
  held_until    TIMESTAMP,
  CONSTRAINT pk_showtime_seats PRIMARY KEY(showtime_id, seat_id),
  CONSTRAINT chk_seat_holder CHECK (
    (status='AVAILABLE' AND booking_id IS NULL AND held_until IS NULL)
    OR (status='HELD' AND booking_id IS NOT NULL AND held_until IS NOT NULL)
    OR (status='SOLD' AND booking_id IS NOT NULL AND held_until IS NULL)
  )
);

-- 10. BẢNG CHI TIẾT GHẾ CỦA ĐƠN ĐẶT VÉ
CREATE TABLE booking_seats (
  booking_id    NUMBER NOT NULL REFERENCES bookings(booking_id),
  seat_id       NUMBER NOT NULL REFERENCES seats(seat_id),
  unit_price    NUMBER(12,0) NOT NULL CHECK(unit_price >= 0),
  CONSTRAINT pk_booking_seats PRIMARY KEY(booking_id, seat_id)
);

-- 11. BẢNG GIAO DỊCH THANH TOÁN (MÔ PHỎNG)
CREATE TABLE payments (
  payment_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  booking_id    NUMBER NOT NULL UNIQUE REFERENCES bookings(booking_id),
  amount        NUMBER(12,0) NOT NULL CHECK(amount >= 0),
  method        VARCHAR2(20) NOT NULL CHECK(method IN ('DEMO_CARD','DEMO_QR','DEMO_CASH')),
  payment_status VARCHAR2(12) DEFAULT 'PAID' NOT NULL CHECK(payment_status IN ('PAID','FAILED')),
  created_at    TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);

-- 12. BẢNG NHẬT KÝ THAY ĐỔI TRẠNG THÁI (AUDIT)
CREATE TABLE booking_audit (
  audit_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  booking_id    NUMBER NOT NULL,
  old_status    VARCHAR2(15),
  new_status    VARCHAR2(15),
  changed_at    TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  description   NVARCHAR2(240)
);

-- CHỈ MỤC TỐI ƯU TRUY VẤN
CREATE INDEX ix_showtime_movie_date ON showtimes(movie_id, start_at);
CREATE INDEX ix_bookings_user_date ON bookings(user_id, created_at);
CREATE INDEX ix_booking_status_expiry ON bookings(status, expires_at);
CREATE INDEX ix_showtime_seats_status ON showtime_seats(showtime_id, status);

-- VIEW 1: CATALOG SUẤT CHIẾU VÀ SỐ GHẾ TRỐNG THỜI GIAN THỰC
CREATE OR REPLACE VIEW v_showtime_catalog AS
SELECT s.showtime_id, s.movie_id, m.title AS movie_title, s.start_at,
       s.end_at, s.base_price, r.room_name, c.cinema_name, c.address,
       (SELECT COUNT(*) FROM showtime_seats ss
         WHERE ss.showtime_id = s.showtime_id AND ss.status = 'AVAILABLE') AS available_seats
FROM showtimes s
JOIN movies m ON m.movie_id = s.movie_id
JOIN rooms r ON r.room_id = s.room_id
JOIN cinemas c ON c.cinema_id = r.cinema_id
WHERE s.is_active = 1 AND m.is_active = 1;

-- VIEW 2: BÁO CÁO ĐƠN ĐẶT VÉ KÈM SỐ LƯỢNG GHẾ
CREATE OR REPLACE VIEW v_booking_report AS
SELECT b.booking_id, b.user_id, u.full_name, b.showtime_id, m.title AS movie_title,
       b.status, b.total_amount, b.created_at, b.expires_at, b.paid_at,
       (SELECT COUNT(*) FROM booking_seats bs WHERE bs.booking_id = b.booking_id) AS seat_count
FROM bookings b
JOIN app_users u ON u.user_id = b.user_id
JOIN showtimes s ON s.showtime_id = b.showtime_id
JOIN movies m ON m.movie_id = s.movie_id;
